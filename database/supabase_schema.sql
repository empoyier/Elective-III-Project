CREATE EXTENSION IF NOT EXISTS btree_gist;

-- 1. Users table (synced with profiles)
CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT,
    license_number TEXT,
    role TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin', 'staff')),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'blocked')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Vehicle Categories
CREATE TABLE IF NOT EXISTS public.vehicle_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Vehicle Inventory
CREATE TABLE IF NOT EXISTS public.vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.vehicle_categories(id) ON DELETE SET NULL,
    brand TEXT NOT NULL,
    model TEXT NOT NULL,
    year INT NOT NULL,
    license_plate TEXT NOT NULL UNIQUE,
    transmission TEXT NOT NULL DEFAULT 'Automatic',
    seats INT NOT NULL DEFAULT 5,
    fuel_type TEXT NOT NULL DEFAULT 'Gasoline',
    mileage INT NOT NULL DEFAULT 0,
    daily_rate NUMERIC(10, 2) NOT NULL,
    image_url TEXT NOT NULL,
    image_credit TEXT,
    operational_status TEXT NOT NULL DEFAULT 'available' CHECK (operational_status IN ('available', 'rented', 'maintenance', 'deactivated')),
    description TEXT,
    features JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Add-ons
CREATE TABLE IF NOT EXISTS public.addons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    daily_rate NUMERIC(10, 2) NOT NULL,
    price_type TEXT NOT NULL DEFAULT 'daily' CHECK (price_type IN ('daily', 'fixed')),
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Bookings
CREATE TABLE IF NOT EXISTS public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_ref TEXT NOT NULL UNIQUE,
    user_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
    vehicle_id BIGINT REFERENCES public.vehicles(id) ON DELETE CASCADE,
    pickup_datetime TIMESTAMPTZ NOT NULL,
    return_datetime TIMESTAMPTZ NOT NULL,
    pickup_location TEXT NOT NULL,
    return_location TEXT NOT NULL,
    total_days INT NOT NULL DEFAULT 1,
    daily_rate NUMERIC(10, 2) NOT NULL,
    base_amount NUMERIC(10, 2) NOT NULL,
    addons_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    tax_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(10, 2) NOT NULL,
    deposit_amount NUMERIC(10, 2) NOT NULL DEFAULT 5000.00,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'out_on_rental', 'returned', 'cancelled', 'rejected')),
    customer_notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.booking_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    booking_id BIGINT NOT NULL REFERENCES public.bookings(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.vehicle_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL UNIQUE REFERENCES public.bookings(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    vehicle_id BIGINT NOT NULL REFERENCES public.vehicles(id) ON DELETE CASCADE,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review_text TEXT CHECK (review_text IS NULL OR char_length(review_text) <= 1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION public.validate_vehicle_review()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM public.bookings b
        WHERE b.id = NEW.booking_id
          AND b.user_id = NEW.user_id
          AND b.vehicle_id = NEW.vehicle_id
          AND b.status = 'returned'
    ) THEN
        RAISE EXCEPTION 'Only the customer who completed a returned booking can review its vehicle.'
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS vehicle_reviews_validate_booking ON public.vehicle_reviews;
CREATE TRIGGER vehicle_reviews_validate_booking
    BEFORE INSERT OR UPDATE ON public.vehicle_reviews
    FOR EACH ROW
    EXECUTE FUNCTION public.validate_vehicle_review();

CREATE OR REPLACE FUNCTION public.create_booking_notification()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    notification_title TEXT;
    notification_message TEXT;
BEGIN
    IF NEW.user_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF TG_OP = 'INSERT' THEN
        notification_title := 'Reservation received';
        notification_message := 'Your reservation ' || NEW.booking_ref || ' was submitted and is pending review.';
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        notification_title := 'Reservation updated';
        notification_message := 'Reservation ' || NEW.booking_ref || ' ' ||
            CASE NEW.status
                WHEN 'pending' THEN 'is pending review.'
                WHEN 'approved' THEN 'has been approved.'
                WHEN 'out_on_rental' THEN 'is now active.'
                WHEN 'returned' THEN 'has been marked as returned.'
                WHEN 'cancelled' THEN 'was cancelled.'
                WHEN 'rejected' THEN 'was rejected.'
                ELSE 'status changed to ' || NEW.status || '.'
            END;
    ELSE
        RETURN NEW;
    END IF;

    INSERT INTO public.booking_notifications (user_id, booking_id, title, message)
    VALUES (NEW.user_id, NEW.id, notification_title, notification_message);

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS bookings_create_notification ON public.bookings;
CREATE TRIGGER bookings_create_notification
    AFTER INSERT OR UPDATE OF status
    ON public.bookings
    FOR EACH ROW
    EXECUTE FUNCTION public.create_booking_notification();

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'bookings_no_overlapping_reservations'
          AND conrelid = 'public.bookings'::regclass
    ) THEN
        ALTER TABLE public.bookings
            ADD CONSTRAINT bookings_no_overlapping_reservations
            EXCLUDE USING gist (
                vehicle_id WITH =,
                tstzrange(pickup_datetime, return_datetime, '[)') WITH &&
            )
            WHERE (status IN ('pending', 'approved', 'out_on_rental'));
    END IF;
END $$;

-- Return inspection fields used by the admin booking workflow. The IF NOT EXISTS
-- clauses also upgrade projects where the bookings table was created previously.
ALTER TABLE public.bookings
    ADD COLUMN IF NOT EXISTS odometer_reading INTEGER,
    ADD COLUMN IF NOT EXISTS fuel_level_returned INTEGER,
    ADD COLUMN IF NOT EXISTS has_damage BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS damage_notes TEXT,
    ADD COLUMN IF NOT EXISTS additional_charges NUMERIC(10, 2) NOT NULL DEFAULT 0.00;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'bookings_odometer_reading_nonnegative'
          AND conrelid = 'public.bookings'::regclass
    ) THEN
        ALTER TABLE public.bookings
            ADD CONSTRAINT bookings_odometer_reading_nonnegative
            CHECK (odometer_reading IS NULL OR odometer_reading >= 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'bookings_fuel_level_returned_range'
          AND conrelid = 'public.bookings'::regclass
    ) THEN
        ALTER TABLE public.bookings
            ADD CONSTRAINT bookings_fuel_level_returned_range
            CHECK (fuel_level_returned IS NULL OR fuel_level_returned BETWEEN 0 AND 100);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'bookings_additional_charges_nonnegative'
          AND conrelid = 'public.bookings'::regclass
    ) THEN
        ALTER TABLE public.bookings
            ADD CONSTRAINT bookings_additional_charges_nonnegative
            CHECK (additional_charges >= 0);
    END IF;
END $$;

-- CREATE TABLE IF NOT EXISTS does not add this relationship to an existing table.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'bookings_user_id_fkey'
          AND conrelid = 'public.bookings'::regclass
    ) THEN
        ALTER TABLE public.bookings
            ADD CONSTRAINT bookings_user_id_fkey
            FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL;
    END IF;
END $$;

-- 6. Booking Add-ons Join Table
CREATE TABLE IF NOT EXISTS public.booking_addons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES public.bookings(id) ON DELETE CASCADE,
    addon_id BIGINT REFERENCES public.addons(id) ON DELETE CASCADE,
    unit_price NUMERIC(10, 2) NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    subtotal NUMERIC(10, 2) NOT NULL
);

-- 7. Maintenance Records
CREATE TABLE IF NOT EXISTS public.maintenance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT REFERENCES public.vehicles(id) ON DELETE CASCADE,
    service_type TEXT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    cost NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'in_progress', 'completed')),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION public.prevent_booking_during_maintenance()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status IN ('pending', 'approved', 'out_on_rental') AND EXISTS (
        SELECT 1
        FROM public.maintenance m
        WHERE m.vehicle_id = NEW.vehicle_id
          AND m.status IN ('scheduled', 'in_progress')
          AND NEW.pickup_datetime < ((m.end_date + 1)::timestamp AT TIME ZONE 'Asia/Manila')
          AND NEW.return_datetime > (m.start_date::timestamp AT TIME ZONE 'Asia/Manila')
    ) THEN
        RAISE EXCEPTION 'Vehicle is scheduled for maintenance during the requested dates.'
            USING ERRCODE = '23P01';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS bookings_check_maintenance ON public.bookings;
CREATE TRIGGER bookings_check_maintenance
    BEFORE INSERT OR UPDATE OF vehicle_id, pickup_datetime, return_datetime, status
    ON public.bookings
    FOR EACH ROW
    EXECUTE FUNCTION public.prevent_booking_during_maintenance();

CREATE OR REPLACE FUNCTION public.prevent_maintenance_during_booking()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status IN ('scheduled', 'in_progress') AND EXISTS (
        SELECT 1
        FROM public.bookings b
        WHERE b.vehicle_id = NEW.vehicle_id
          AND b.status IN ('pending', 'approved', 'out_on_rental')
          AND b.pickup_datetime < ((NEW.end_date + 1)::timestamp AT TIME ZONE 'Asia/Manila')
          AND b.return_datetime > (NEW.start_date::timestamp AT TIME ZONE 'Asia/Manila')
    ) THEN
        RAISE EXCEPTION 'Maintenance period overlaps an active reservation.'
            USING ERRCODE = '23P01';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS maintenance_check_bookings ON public.maintenance;
CREATE TRIGGER maintenance_check_bookings
    BEFORE INSERT OR UPDATE OF vehicle_id, start_date, end_date, status
    ON public.maintenance
    FOR EACH ROW
    EXECUTE FUNCTION public.prevent_maintenance_during_booking();

