ALTER TABLE public.addons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.booking_addons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.maintenance ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public all on users" ON public.users;
DROP POLICY IF EXISTS "Allow public all on vehicle_categories" ON public.vehicle_categories;
DROP POLICY IF EXISTS "Allow public all on vehicles" ON public.vehicles;
DROP POLICY IF EXISTS "Allow public all on addons" ON public.addons;
DROP POLICY IF EXISTS "Allow public all on bookings" ON public.bookings;
DROP POLICY IF EXISTS "Allow public all on booking_addons" ON public.booking_addons;
DROP POLICY IF EXISTS "Allow public all on maintenance" ON public.maintenance;

CREATE POLICY "Allow public all on users" ON public.users FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on vehicle_categories" ON public.vehicle_categories FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on vehicles" ON public.vehicles FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on addons" ON public.addons FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on bookings" ON public.bookings FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on booking_addons" ON public.booking_addons FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all on maintenance" ON public.maintenance FOR ALL USING (true) WITH CHECK (true);

